"""AI endpoints: goal planner and motivation chat.

If Claude is unavailable (no key, rate limit, network error, bad output) the
endpoints still answer, but the response is explicitly marked
`ai_generated: false` and `source: "fallback"` with a `notice` explaining why.
"""
from datetime import date

from flask import Blueprint, current_app, g, jsonify, request

from extensions import db
from models import ChatMessage, Goal
from models.mixins import iso, utcnow
from services.claude_service import AIServiceError, build_fallback_chat_reply, build_template_plan
from utils.auth import require_auth
from utils.http import api_error, invalid_json, json_body, validation_error
from utils.validators import validate_chat_message, validate_plan_request

ai_bp = Blueprint("ai", __name__, url_prefix="/api/ai")


def _service():
    return current_app.extensions["claude_service"]


def _rate_limited():
    """True if this user has made too many AI requests recently."""
    return not current_app.extensions["gm_limiters"]["ai"].hit(str(g.current_user.id))


def _build_context(user, goal_id=None) -> str:
    """Short summary of the user's goals sent to Claude to personalise chat answers."""
    goals = Goal.query.filter_by(user_id=user.id, status="active").limit(8).all()
    lines = []
    for goal in goals:
        progress = goal.progress()
        due = goal.target_date.isoformat() if goal.target_date else "no date"
        lines.append(
            f'- "{goal.title}" ({goal.category}, {goal.priority} priority, due {due}): '
            f"{progress['completed_missions']}/{progress['total_missions']} missions done, "
            f"{progress['overdue_missions']} overdue"
        )
    if goal_id:
        focus = Goal.query.filter_by(id=goal_id, user_id=user.id).first()
        if focus:
            lines.append(f'The user is currently asking about the goal "{focus.title}".')
    return f"Today is {date.today().isoformat()}.\n" + ("\n".join(lines) if lines else "The user has no active goals yet.")


@ai_bp.get("/status")
@require_auth
def status():
    service = _service()
    return jsonify(
        {
            "ai_available": service.is_available,
            "mode": "claude" if service.is_available else "fallback",
            "model": service.model if service.is_available else None,
            "message": None if service.is_available
            else f"AI is off ({service.unavailable_reason()}). Template responses will be clearly labelled as not AI-generated.",
        }
    )


@ai_bp.post("/plan")
@require_auth
def generate_plan():
    data = json_body()
    if data is None:
        return invalid_json()
    params, errors = validate_plan_request(data)
    if errors:
        return validation_error(errors)
    if _rate_limited():
        return api_error("You are making AI requests too quickly. Please wait a few minutes.", 429, "rate_limited")

    service = _service()
    today = date.today()
    try:
        plan = service.generate_plan(params, today=today)
        source, notice, model = "claude", None, service.model
    except AIServiceError as exc:
        current_app.logger.warning("AI plan fallback used (%s): %s", exc.reason, exc.message)
        plan = build_template_plan(params, today)
        source, model = "fallback", None
        notice = (
            f"AI plan unavailable ({exc.message}). This is a simple template plan, "
            "NOT generated by AI. Edit it to fit your goal."
        )
    return jsonify(
        {
            "plan": plan,
            "source": source,
            "ai_generated": source == "claude",
            "model": model,
            "notice": notice,
            "request": {**params, "deadline": params["deadline"].isoformat()},
            "generated_at": iso(utcnow()),
        }
    )


@ai_bp.post("/chat")
@require_auth
def chat():
    data = json_body()
    if data is None:
        return invalid_json()
    clean, errors = validate_chat_message(data)
    if errors:
        return validation_error(errors)
    if _rate_limited():
        return api_error("You are sending messages too quickly. Please wait a moment.", 429, "rate_limited")

    user = g.current_user
    # Only real AI replies are sent back to Claude as history (never fallback text).
    recent = (
        ChatMessage.query.filter_by(user_id=user.id)
        .order_by(ChatMessage.id.desc()).limit(12).all()
    )
    history = [
        {"role": m.role, "content": m.content}
        for m in reversed(recent)
        if m.role == "user" or m.source == "claude"
    ]

    user_message = ChatMessage(user_id=user.id, role="user", content=clean["message"], source="user")
    db.session.add(user_message)
    db.session.commit()

    service = _service()
    try:
        reply_text = service.chat(history, clean["message"], _build_context(user, clean["goal_id"]))
        source, notice = "claude", None
    except AIServiceError as exc:
        current_app.logger.warning("AI chat fallback used (%s): %s", exc.reason, exc.message)
        reply_text = build_fallback_chat_reply(clean["message"], exc.message)
        source = "fallback"
        notice = f"AI unavailable ({exc.message}). This reply is NOT AI-generated."

    reply = ChatMessage(user_id=user.id, role="assistant", content=reply_text, source=source)
    db.session.add(reply)
    db.session.commit()
    return jsonify(
        {
            "user_message": user_message.to_dict(),
            "reply": reply.to_dict(),
            "ai_generated": source == "claude",
            "notice": notice,
        }
    )


@ai_bp.get("/chat/history")
@require_auth
def chat_history():
    try:
        limit = min(max(int(request.args.get("limit", 50)), 1), 200)
    except ValueError:
        limit = 50
    rows = (
        ChatMessage.query.filter_by(user_id=g.current_user.id)
        .order_by(ChatMessage.id.desc()).limit(limit).all()
    )
    return jsonify({"messages": [m.to_dict() for m in reversed(rows)]})


@ai_bp.delete("/chat/history")
@require_auth
def clear_chat_history():
    ChatMessage.query.filter_by(user_id=g.current_user.id).delete()
    db.session.commit()
    return jsonify({"message": "Conversation cleared."})
