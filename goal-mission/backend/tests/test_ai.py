"""AI planner / chat tests. The Claude API is never called - a fake service is injected."""
from datetime import date, timedelta

import pytest

from conftest import FakeClaude
from services.claude_service import (
    AIResponseError,
    AIServiceError,
    build_template_plan,
    extract_json,
    validate_plan,
)

DEADLINE = (date.today() + timedelta(days=14)).isoformat()
PLAN_REQUEST = {"goal": "Learn SQL", "hours_per_week": 5, "skill_level": "beginner", "deadline": DEADLINE}


def good_plan():
    return {
        "goal_description": "Learn SQL basics.",
        "action_plan": ["Learn SELECT", "Practice joins"],
        "missions": [
            {"title": "Learn SELECT", "description": "x", "estimated_minutes": 60,
             "suggested_due_date": (date.today() + timedelta(days=3)).isoformat(), "priority": "high"},
        ],
        "obstacles": [{"obstacle": "Time", "solution": "Schedule it"}],
        "motivation": "You can do it.",
    }


def test_ai_status_reports_fallback_without_key(client, auth):
    body = client.get("/api/ai/status", headers=auth).get_json()
    assert body["ai_available"] is False and body["mode"] == "fallback"


def test_plan_requires_valid_input(client, auth):
    response = client.post("/api/ai/plan", json={"goal": "", "hours_per_week": 0, "deadline": "2001-01-01"}, headers=auth)
    assert response.status_code == 422
    assert {"goal", "hours_per_week", "deadline"} <= set(response.get_json()["error"]["details"])


def test_plan_uses_claude_when_available(client, app, auth):
    fake = FakeClaude(plan=good_plan())
    app.extensions["claude_service"] = fake
    body = client.post("/api/ai/plan", json=PLAN_REQUEST, headers=auth).get_json()
    assert body["ai_generated"] is True and body["source"] == "claude" and body["notice"] is None
    assert body["plan"]["missions"][0]["title"] == "Learn SELECT"
    assert fake.calls == 1


def test_plan_falls_back_and_is_labelled_when_claude_fails(client, app, auth):
    app.extensions["claude_service"] = FakeClaude(error=AIServiceError("the Claude API rate limit was reached", "rate_limit"))
    response = client.post("/api/ai/plan", json=PLAN_REQUEST, headers=auth)
    assert response.status_code == 200
    body = response.get_json()
    assert body["ai_generated"] is False and body["source"] == "fallback"
    assert "NOT generated by AI" in body["notice"]
    assert len(body["plan"]["missions"]) >= 4


def test_plan_falls_back_when_no_api_key_configured(client, auth):
    body = client.post("/api/ai/plan", json=PLAN_REQUEST, headers=auth).get_json()
    assert body["source"] == "fallback" and body["ai_generated"] is False


def test_chat_stores_history_and_labels_fallback(client, app, auth):
    app.extensions["claude_service"] = FakeClaude()
    real = client.post("/api/ai/chat", json={"message": "I keep procrastinating"}, headers=auth).get_json()
    assert real["ai_generated"] is True and real["reply"]["source"] == "claude"

    app.extensions["claude_service"] = FakeClaude(error=AIServiceError("could not connect", "connection"))
    fallback = client.post("/api/ai/chat", json={"message": "I keep procrastinating"}, headers=auth).get_json()
    assert fallback["ai_generated"] is False and fallback["reply"]["source"] == "fallback"
    assert "NOT an AI answer" in fallback["reply"]["content"]

    history = client.get("/api/ai/chat/history", headers=auth).get_json()["messages"]
    assert [m["role"] for m in history] == ["user", "assistant", "user", "assistant"]
    assert client.delete("/api/ai/chat/history", headers=auth).status_code == 200
    assert client.get("/api/ai/chat/history", headers=auth).get_json()["messages"] == []


def test_chat_history_is_private_per_user(client, app, auth, other_auth):
    app.extensions["claude_service"] = FakeClaude()
    client.post("/api/ai/chat", json={"message": "secret plan"}, headers=auth)
    assert client.get("/api/ai/chat/history", headers=other_auth).get_json()["messages"] == []


def test_chat_validation(client, auth):
    assert client.post("/api/ai/chat", json={"message": "   "}, headers=auth).status_code == 422
    assert client.post("/api/ai/chat", json={"message": "x" * 2001}, headers=auth).status_code == 422


def test_ai_endpoints_require_login(client):
    assert client.post("/api/ai/plan", json=PLAN_REQUEST).status_code == 401
    assert client.post("/api/ai/chat", json={"message": "hi"}).status_code == 401


# ---------- pure-function tests for the validation of AI output ----------
def test_extract_json_handles_code_fences_and_prose():
    assert extract_json('```json\n{"a": 1}\n```') == {"a": 1}
    assert extract_json('Sure! Here you go: {"a": 2} Hope it helps') == {"a": 2}
    with pytest.raises(AIResponseError):
        extract_json("no json here")


def test_validate_plan_sanitises_and_clamps_dates():
    today = date.today()
    deadline = today + timedelta(days=10)
    raw = {
        "missions": [
            {"title": "Late", "estimated_minutes": 99999, "priority": "URGENT",
             "suggested_due_date": (today + timedelta(days=50)).isoformat()},
            {"title": "Past", "estimated_minutes": "abc", "suggested_due_date": "2000-01-01"},
            {"title": "", "description": "dropped: no title"},
            "not a dict",
        ]
    }
    plan = validate_plan(raw, today, deadline)
    assert len(plan["missions"]) == 2
    first, second = plan["missions"]
    assert first["estimated_minutes"] == 1440 and first["priority"] == "medium"
    assert first["suggested_due_date"] == deadline.isoformat()  # clamped to the deadline
    assert second["estimated_minutes"] == 60
    assert second["suggested_due_date"] >= first["suggested_due_date"]  # never goes backwards
    assert plan["action_plan"]  # derived when missing


def test_validate_plan_rejects_unusable_output():
    today = date.today()
    with pytest.raises(AIResponseError):
        validate_plan("a string", today, today)
    with pytest.raises(AIResponseError):
        validate_plan({"missions": []}, today, today)
    with pytest.raises(AIResponseError):
        validate_plan({"missions": [{"description": "no title"}]}, today, today)


def test_template_plan_respects_deadline():
    today = date.today()
    deadline = today + timedelta(days=20)
    plan = build_template_plan(
        {"goal": "Write thesis", "hours_per_week": 6, "skill_level": "beginner", "deadline": deadline}, today
    )
    dates = [m["suggested_due_date"] for m in plan["missions"]]
    assert dates == sorted(dates) and dates[-1] == deadline.isoformat()
    assert all(m["estimated_minutes"] >= 15 for m in plan["missions"])
