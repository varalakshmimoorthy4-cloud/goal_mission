import { useEffect, useRef, useState } from "react";
import { Bot, Send, Sparkles, Trash2, TriangleAlert, User } from "lucide-react";
import { api, ApiError } from "../api/client";
import { useToast } from "../context/ToastContext";
import useDocumentTitle from "../hooks/useDocumentTitle";
import ConfirmDialog from "../components/ConfirmDialog";
import LoadingSpinner from "../components/LoadingSpinner";
import { timeAgo } from "../utils/format";

const STARTERS = [
  "I keep procrastinating on my most important goal. Where do I start?",
  "Help me break a big assignment into smaller steps.",
  "My plan feels unrealistic. How can I adjust it?",
  "I'm losing motivation because progress is slow.",
];

function Message({ message }) {
  const isUser = message.role === "user";
  return (
    <div className={`chat-row ${isUser ? "user" : "assistant"}`}>
      <span className="chat-avatar" aria-hidden="true">{isUser ? <User size={16} /> : <Bot size={16} />}</span>
      <div className="chat-bubble-wrap">
        <div className={`chat-bubble ${!isUser && message.source === "fallback" ? "fallback" : ""}`}>{message.content}</div>
        <div className="chat-meta">
          {!isUser && message.source === "claude" && <span className="ai-label"><Sparkles size={12} aria-hidden="true" /> AI-generated by Claude</span>}
          {!isUser && message.source === "fallback" && <span className="fallback-label"><TriangleAlert size={12} aria-hidden="true" /> Not AI - pre-written tips</span>}
          {message.created_at && <time dateTime={message.created_at}>{timeAgo(message.created_at)}</time>}
        </div>
      </div>
    </div>
  );
}

export default function AIChat() {
  useDocumentTitle("Motivation Assistant");
  const toast = useToast();
  const [messages, setMessages] = useState(null);
  const [goals, setGoals] = useState([]);
  const [goalId, setGoalId] = useState("");
  const [input, setInput] = useState("");
  const [sending, setSending] = useState(false);
  const [error, setError] = useState("");
  const [aiStatus, setAiStatus] = useState(null);
  const [confirmClear, setConfirmClear] = useState(false);
  const endRef = useRef(null);

  useEffect(() => {
    api.ai.history().then((d) => setMessages(d.messages)).catch((e) => { setMessages([]); setError(e.message); });
    api.ai.status().then(setAiStatus).catch(() => {});
    api.goals.list({ status: "active" }).then((d) => setGoals(d.goals)).catch(() => {});
  }, []);

  useEffect(() => {
    endRef.current?.scrollIntoView({ behavior: "smooth", block: "end" });
  }, [messages, sending]);

  const send = async (text) => {
    const message = text.trim();
    if (!message || sending) return;
    if (message.length > 2000) return setError("Message must be at most 2000 characters.");

    setError("");
    setSending(true);
    const pending = { id: `pending-${Date.now()}`, role: "user", content: message, source: "user", created_at: new Date().toISOString() };
    setMessages((list) => [...list, pending]);
    setInput("");
    try {
      const data = await api.ai.chat(message, goalId);
      setMessages((list) => [...list.filter((m) => m.id !== pending.id), data.user_message, data.reply]);
      if (data.notice) toast.info(data.notice);
    } catch (err) {
      // Roll back the optimistic message and give the text back so nothing is lost.
      setMessages((list) => list.filter((m) => m.id !== pending.id));
      setInput(message);
      setError(err instanceof ApiError ? err.message : "Could not send your message.");
    } finally {
      setSending(false);
    }
  };

  const handleKeyDown = (event) => {
    if (event.key === "Enter" && !event.shiftKey) {
      event.preventDefault();
      send(input);
    }
  };

  const clearHistory = async () => {
    try {
      await api.ai.clearHistory();
      setMessages([]);
      toast.success("Conversation cleared.");
    } catch (err) {
      toast.error(err.message);
    } finally {
      setConfirmClear(false);
    }
  };

  return (
    <>
      <div className="page-header">
        <div>
          <h1>Motivation Assistant</h1>
          <p className="page-sub">Get help with procrastination, planning, study habits and staying motivated.</p>
        </div>
        <button className="btn btn-secondary btn-sm" onClick={() => setConfirmClear(true)} disabled={!messages?.length}>
          <Trash2 size={15} aria-hidden="true" /> Clear conversation
        </button>
      </div>

      {aiStatus && !aiStatus.ai_available && (
        <div className="banner banner-warn" role="note">
          <TriangleAlert size={18} aria-hidden="true" />
          <span>The AI is not configured, so replies are <strong>pre-written tips, not AI answers</strong>. See the README to enable Claude.</span>
        </div>
      )}

      <section className="card chat-card" aria-label="Conversation">
        <div className="chat-log" role="log" aria-live="polite">
          {!messages && <LoadingSpinner block label="Loading conversation..." />}
          {messages && messages.length === 0 && (
            <div className="chat-empty">
              <span className="empty-icon"><Bot size={28} aria-hidden="true" /></span>
              <h2>How can I help today?</h2>
              <p className="muted">Pick a starter or type your own message.</p>
              <div className="chip-row">
                {STARTERS.map((s) => (
                  <button key={s} className="chip" onClick={() => send(s)} disabled={sending}>{s}</button>
                ))}
              </div>
            </div>
          )}
          {messages && messages.map((m) => <Message key={m.id} message={m} />)}
          {sending && (
            <div className="chat-row assistant" role="status" aria-label="The assistant is thinking">
              <span className="chat-avatar" aria-hidden="true"><Bot size={16} /></span>
              <div className="chat-bubble typing"><span /><span /><span /></div>
            </div>
          )}
          <div ref={endRef} />
        </div>

        {error && <div className="banner banner-danger" role="alert">{error}</div>}

        <form className="chat-form" onSubmit={(e) => { e.preventDefault(); send(input); }}>
          {goals.length > 0 && (
            <div className="chat-context">
              <label htmlFor="chat-goal" className="muted small">Ask about:</label>
              <select id="chat-goal" className="select select-sm" value={goalId} onChange={(e) => setGoalId(e.target.value)}>
                <option value="">All my goals</option>
                {goals.map((g) => <option key={g.id} value={g.id}>{g.title}</option>)}
              </select>
            </div>
          )}
          <div className="chat-input-row">
            <label htmlFor="chat-input" className="sr-only">Your message</label>
            <textarea
              id="chat-input"
              className="textarea"
              rows={2}
              maxLength={2000}
              placeholder="Type your message... (Enter to send, Shift+Enter for a new line)"
              value={input}
              onChange={(e) => setInput(e.target.value)}
              onKeyDown={handleKeyDown}
            />
            <button type="submit" className="btn btn-primary" disabled={sending || !input.trim()} aria-label="Send message">
              <Send size={18} aria-hidden="true" />
            </button>
          </div>
          <p className="hint">
            {aiStatus?.ai_available
              ? "Your message and a short summary of your active goals are sent to Claude (Anthropic). The assistant is not a substitute for professional advice."
              : "Conversation history is saved to your account."}
          </p>
        </form>
      </section>

      {confirmClear && (
        <ConfirmDialog
          title="Clear conversation?"
          message="All messages in this conversation will be permanently deleted."
          confirmLabel="Clear"
          onCancel={() => setConfirmClear(false)}
          onConfirm={clearHistory}
        />
      )}
    </>
  );
}
